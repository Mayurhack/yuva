function applyLanguage(lang) {
    if (!translations[lang]) lang = 'en';
    localStorage.setItem('lang', lang);

    // Update html lang attribute
    document.documentElement.setAttribute('lang', lang);

    // Set select dropdown value
    const langSelect = document.getElementById('lang-select');
    if (langSelect) {
        langSelect.value = lang;
    }

    // Translate all elements with data-i18n attribute
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            // Check if it's an input or textarea (for placeholders)
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                if (key.includes('placeholder')) {
                    el.placeholder = translations[lang][key];
                }
            } else if (el.tagName === 'OPTION') {
                el.textContent = translations[lang][key];
            } else {
                // For HTML tags (to preserve strong/span tags if needed)
                if (translations[lang][key].includes('<') && translations[lang][key].includes('>')) {
                    el.innerHTML = translations[lang][key];
                } else {
                    el.textContent = translations[lang][key];
                }
            }
        }
    });

    // Also translate any placeholders that might have specific data-i18n-placeholder attribute
    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });
}

document.addEventListener('DOMContentLoaded', () => {
    const defaultLang = localStorage.getItem('lang') || 'en';
    
    // Bind change event to select dropdown
    const langSelect = document.getElementById('lang-select');
    if (langSelect) {
        langSelect.addEventListener('change', (e) => {
            applyLanguage(e.target.value);
        });
    }

    applyLanguage(defaultLang);
});
